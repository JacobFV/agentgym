// Generate RESULTS.md purely from recorded artifacts (no hand-entered numbers).
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
const root = new URL("../", import.meta.url).pathname;
const dir = root + "results/evolutions/";
const runs = readdirSync(dir).filter((f) => /^evo-.*\.json$/.test(f)).sort().map((f) => JSON.parse(readFileSync(dir + f, "utf8")));
const L = ["# results", "", "Generated by `node scripts/results.mjs` from `results/evolutions/*.json`. Every number below comes from an actual recorded execution.", ""];
L.push("| run | coder | mutator | dev pass (parent) | subq recurring weakness | candidates | validation parent → candidates | decision |", "|---|---|---|---|---|---|---|---|");
for (const r of runs) {
  L.push(`| ${r.runId} | ${r.coder.id}:${r.coder.model} | ${r.mutator.id}:${r.mutator.model} | ${r.devTotals.runPasses}/${r.devTotals.runs} | ${r.diagnosis.recurring.weakness} (p=${r.diagnosis.recurring.probabilities[r.diagnosis.recurring.weakness].toFixed(2)}) | ${r.proposals.length} | ${r.parentVal.totals.runPasses}/${r.parentVal.totals.runs} → ${r.candidateVals.map((c) => `${c.version}:${c.totals.runPasses}/${c.totals.runs}`).join(", ")} | ${r.promoted ? "PROMOTE " + r.promoted : "REJECT all"} |`);
}
for (const r of runs) {
  L.push("", `## ${r.runId}`, "", "```", readFileSync(dir + r.runId + ".md", "utf8"), "```");
}
const finals = existsSync(root + "results/final") ? readdirSync(root + "results/final").filter((f) => f.endsWith(".md")) : [];
for (const f of finals) L.push("", readFileSync(root + "results/final/" + f, "utf8"));
writeFileSync(root + "RESULTS.md", L.join("\n") + "\n");
console.log(L.slice(0, 4 + runs.length + 2).join("\n"));
